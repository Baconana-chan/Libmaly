/**
 * Dynamically add a custom language pack at runtime.
 * The JSON should have the same structure as the built-in translations:
 * { "common": {...}, "settings": {...}, "game": {...}, ... }
 */
export function addCustomLanguage(code: string, name: string, translation: Record<string, unknown>) {
  i18n.addResourceBundle(code, "translation", translation, true, true);
  // Store in localStorage so it persists across sessions
  try {
    const stored = JSON.parse(localStorage.getItem("libmaly_custom_languages") || "{}");
    stored[code] = { name, translation };
    localStorage.setItem("libmaly_custom_languages", JSON.stringify(stored));
  } catch { /* ignore */ }
}

/**
 * Load all custom languages from localStorage.
 * Returns a map of { code: { name, translation } }.
 */
export function loadCustomLanguages(): Record<string, { name: string; translation: Record<string, unknown> }> {
  try {
    return JSON.parse(localStorage.getItem("libmaly_custom_languages") || "{}");
  } catch {
    return {};
  }
}

/**
 * Remove a custom language pack.
 */
export function removeCustomLanguage(code: string) {
  i18n.removeResourceBundle(code, "translation");
  try {
    const stored = JSON.parse(localStorage.getItem("libmaly_custom_languages") || "{}");
    delete stored[code];
    localStorage.setItem("libmaly_custom_languages", JSON.stringify(stored));
  } catch { /* ignore */ }
}

